SELECT governorate.id,
       district.code,
       district.name_ar,
       district.name_en,
       'district',
       district.is_active
FROM source_districts AS district
JOIN source_governorate_mapping AS mapping
  ON mapping.source_code = district.parent_source_code
JOIN public.governorates AS governorate
  ON governorate.code = mapping.production_code
ON CONFLICT (code) DO UPDATE
SET governorate_id = EXCLUDED.governorate_id,
    name_ar = EXCLUDED.name_ar,
    name_en = EXCLUDED.name_en,
    area_type = EXCLUDED.area_type,
    is_active = EXCLUDED.is_active;
